"""Append-only revisions with optimistic concurrency, not a reasoning runtime."""
from __future__ import annotations

import difflib
import json
import os
import re
import sqlite3
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

STATUSES = {'reference', 'candidate', 'adopted', 'inactive', 'uncertain'}
# Tells the host how to use an asset; the order is the catalog and export order.
TYPES = ('boundary', 'context', 'principle', 'method', 'pattern')
# Core assets are returned in full on every catalog call, so they cost context every time.
CORE_LIMIT = 10
# Hosts keep always-loaded files short (Claude Code: under 200 lines per CLAUDE.md); a core entry stays one idea.
BRIEF_LINE_BUDGET = 200
CORE_CHAR_BUDGET = 2000
EXPORT_BEGIN = '<!-- BEGIN MYOS BRIEF: generated by `myos compile`; edit assets, not this block -->'
EXPORT_END = '<!-- END MYOS BRIEF -->'
BRIEF_PREAMBLE = (
    "Generated from the owner's MyOS store. Core entries are shown in full; every other adopted entry is listed with the situation it applies to. "
    "When a listed situation fits the task, read that entry's full text with the MyOS tools before answering, or apply its title if the tools are unavailable. "
    "Apply an entry only where its Applies line fits, within its Limits; when unsure whether a boundary applies, treat it as applying. "
    "Precedence: the owner's current explicit instruction, then boundaries, then principles and methods (the more specific applicability wins), then patterns. "
    "A pattern is a tendency of the owner: point it out when it works against the owner's interests; it is never a rule to follow. Context informs. "
    "Stakes set the depth of analysis only; boundaries and approval steps apply at any stakes. Examples illustrate an entry; do not copy their moves. "
    "These entries never grant permission for an external action.")


def asset_type(asset):
    kind = asset.get('type')
    return kind if kind in TYPES else 'unclassified'


def is_core(asset):
    return asset.get('core') is True and asset.get('status') == 'adopted'


def type_order(asset):
    kind = asset_type(asset)
    return (TYPES.index(kind) if kind in TYPES else len(TYPES), asset['id'])


def marker_safe(value):
    """Asset text must not be able to open or close the exported block."""
    return str(value).replace('<!--', '&lt;!--')


CASE_ID = re.compile(r'^[A-Za-z0-9_-]+$')
CASES_DIR = Path('evals') / 'cases'


def case_errors(case):
    """A `myos eval` case must satisfy what the blind review checks: every need quotes its evidence from `source`."""
    if not isinstance(case, dict):
        return ['Case must be an object']
    errors = [f'Case needs a nonempty {k}' for k in ('id', 'date', 'prompt', 'source') if not (isinstance(case.get(k), str) and case[k].strip())]
    if isinstance(case.get('id'), str) and not CASE_ID.match(case['id']):
        errors.append('Case id must be letters, digits, _ or -')
    if not isinstance(case.get('negative_control', False), bool) or not isinstance(case.get('retired', False), bool):
        errors.append('negative_control and retired must be true or false')
    needs = case.get('needs')
    if not (isinstance(needs, list) and needs and all(isinstance(n, dict) for n in needs)):
        return errors + ['Case needs a nonempty list of needs']
    ids = [n.get('id') for n in needs]
    if any(not (isinstance(i, str) and i.strip()) for i in ids) or len(set(ids)) != len(ids):
        errors.append('Need ids must be unique nonempty strings')
    for n in needs:
        if any(not (isinstance(n.get(k), str) and n[k].strip()) for k in ('description', 'rationale', 'source_quote')):
            errors.append(f"Need {n.get('id')}: description, rationale and source_quote are required")
        elif not isinstance(case.get('source'), str) or n['source_quote'] not in case['source']:
            errors.append(f"Need {n.get('id')}: source_quote must be copied exactly from source")
        if not isinstance(n.get('condition', ''), str) or not isinstance(n.get('assets', []), list) or not all(isinstance(a, str) for a in n.get('assets', [])):
            errors.append(f"Need {n.get('id')}: condition must be a string and assets a list of entry ids")
    if all(isinstance(n.get('condition'), str) and n['condition'].strip() for n in needs):
        errors.append('A case needs at least one unconditional need')
    return errors


def field_errors(asset):
    """Value checks for the fields that tell hosts how to use an asset."""
    errors = []
    if 'type' in asset and asset['type'] not in TYPES:
        errors.append(f"Type must be one of {', '.join(TYPES)}")
    if 'core' in asset and not isinstance(asset['core'], bool):
        errors.append('Core must be true or false')
    if asset.get('core') is True and asset.get('status') != 'adopted':
        errors.append('Only adopted assets can be core')
    if asset.get('core') is True and asset.get('type') not in TYPES:
        errors.append('Core assets need a type')
    examples = asset.get('examples', [])
    if not isinstance(examples, list) or any(not isinstance(e, dict) or not isinstance(e.get('text'), str) or not e['text'].strip()
                                             or not isinstance(e.get('source'), str) or not e['source'].strip() for e in examples):
        errors.append('Examples must be a list of {text, source} with nonempty strings')
    return errors


def quote_changes(previous, asset):
    """Examples of the previous revision that the new one no longer contains verbatim.

    Examples are often the owner's exact words, kept as evidence. A host that retypes a quote instead of copying it can
    silently alter it, so each write reports every earlier example missing from the new revision: with the closest new
    example from the same source as `after` when one resembles it (an edited quote), otherwise `after` is null (removed).
    """
    old = [e for e in (previous or {}).get('examples', []) if isinstance(e, dict)]
    new = [e for e in asset.get('examples', []) if isinstance(e, dict)]
    kept, added = {e['text'] for e in new}, [e for e in new if e['text'] not in {o['text'] for o in old}]
    changes = []
    for o in old:
        if o['text'] in kept:
            continue
        candidates = [(difflib.SequenceMatcher(None, o['text'], e['text']).ratio(), e['text']) for e in added if e.get('source') == o.get('source')]
        ratio, after = max(candidates, default=(0, None))
        changes.append({'source': o.get('source'), 'before': o['text'], 'after': after if ratio >= 0.6 else None})
    return changes


class Store:
    def __init__(self, root: Path):
        self.root = Path(root)
        self.path = self.root / 'cognition.sqlite3'

    def connect(self, *, write=False):
        if write:
            self.root.mkdir(parents=True, exist_ok=True, mode=0o700)
            db = sqlite3.connect(self.path)
            self.path.chmod(0o600)
            db.execute('CREATE TABLE IF NOT EXISTS revisions (id TEXT NOT NULL, revision INTEGER NOT NULL, recorded_at TEXT NOT NULL, body TEXT NOT NULL, authorization TEXT NOT NULL, PRIMARY KEY(id, revision))')
            db.execute('CREATE TABLE IF NOT EXISTS cases (id TEXT PRIMARY KEY, asset_id TEXT NOT NULL, revision INTEGER NOT NULL, recorded_at TEXT NOT NULL, body TEXT NOT NULL)')
            db.commit()
            return db
        return sqlite3.connect(f'{self.path.as_uri()}?mode=ro', uri=True)

    def current(self):
        """Latest revision of every asset, including inactive ones."""
        if not self.path.exists():
            return []
        with self.connect() as db:
            rows = db.execute('SELECT body, revision FROM revisions r WHERE revision=(SELECT MAX(revision) FROM revisions WHERE id=r.id)').fetchall()
        return sorted((dict(json.loads(body), revision=n) for body, n in rows), key=type_order)

    def catalog(self):
        """Keep candidates indexed for correction matching; hosts skip them when answering."""
        active = [a for a in self.current() if a['status'] != 'inactive']
        core = [dict({k: a[k] for k in ('id', 'title', 'content', 'applicability', 'boundaries', 'basis', 'examples', 'status', 'revision') if k in a},
                     type=asset_type(a)) for a in active if is_core(a)]
        index = [dict(id=a['id'], title=a['title'], type=asset_type(a), status=a['status'], applicability=a['applicability'], revision=a['revision'])
                 for a in active if not is_core(a)]
        return {'core': core, 'index': index}

    def compile(self):
        """Markdown block for a host's always-loaded instructions: core assets in full, one line per other adopted asset.

        Hosts keep always-loaded files short, so only the owner's core set is in full; the index line tells the host
        when to read the rest. No revisions, basis, sources, timestamps or examples: examples are often the owner's
        verbatim corrections, kept as evidence for the catalog and reads, not as rules. Candidates are indexed only for
        correction matching, never for answers; uncertain and reference assets stay behind the catalog as material.
        """
        if not self.path.exists():
            raise ValueError('No cognition store; initialize through an authorized write or migration')
        adopted = [a for a in self.current() if a['status'] == 'adopted']
        core, other = [a for a in adopted if is_core(a)], [a for a in adopted if not is_core(a)]
        lines = [EXPORT_BEGIN, "## MyOS: the owner's self-model", '', BRIEF_PREAMBLE, '']
        if not adopted:
            lines += ['No adopted assets yet.', '']
        if core:
            lines += ['## Core (always applies where it fits)', '']
        for a in core:
            lines += [f"### {marker_safe(a['title'])} ({asset_type(a)})", '', marker_safe(a['content']), '', f"- Applies: {marker_safe(a['applicability'])}"]
            lines += [f'- Limits: {marker_safe(b)}' for b in a['boundaries']]
            lines.append('')
        if other:
            lines += ['## Other entries (read in full when the situation fits)', '']
            lines += [f"- {marker_safe(a['title'])} ({asset_type(a)}, id `{marker_safe(a['id'])}`): {marker_safe(a['applicability'])}" for a in other]
            lines.append('')
        lines.append(EXPORT_END)
        return '\n'.join(lines) + '\n'

    def read(self, asset_id, *, history=False):
        with self.connect() as db:
            rows = db.execute('SELECT revision, recorded_at, body, authorization FROM revisions WHERE id=? ORDER BY revision', (asset_id,)).fetchall()
        if not rows:
            raise ValueError(f'Unknown asset: {asset_id}')
        result = [dict(json.loads(body), revision=n, recorded_at=t, authorization=json.loads(auth)) for n, t, body, auth in rows]
        # The current asset keeps what a host applies or revises (sources included); history adds each write record.
        return result if history else {k: v for k, v in result[-1].items() if k not in ('recorded_at', 'authorization')}

    def put(self, asset, *, expected_revision, authorization, case=None):
        required = {'id', 'title', 'content', 'applicability', 'boundaries', 'status', 'basis', 'sources'}
        if not required <= asset.keys():
            raise ValueError(f'Missing fields: {sorted(required - asset.keys())}')
        if any(not isinstance(asset[k], str) or not asset[k].strip() for k in ('id', 'title', 'content', 'applicability', 'basis')):
            raise ValueError('Identity, content, applicability and basis must be nonempty strings')
        if asset['status'] not in STATUSES or not isinstance(asset['boundaries'], list):
            raise ValueError('Invalid status or boundaries')
        if not isinstance(asset['sources'], list) or not asset['sources'] or any(not isinstance(s, dict) or not s.get('ref') for s in asset['sources']):
            raise ValueError('Sources require provenance references')
        if not isinstance(authorization, dict) or not authorization.get('request') or not authorization.get('source'):
            raise ValueError('A host-verified owner request and its source are required for writes')
        if authorization.get('mode') == 'migration' and asset['status'] == 'adopted' and not asset.get('legacy_adoption_evidence'):
            raise ValueError('Migration cannot infer adoption')
        # Candidates retain their intended type for possible adoption; reference and inactive may omit it.
        if 'type' not in asset and asset['status'] not in ('reference', 'inactive') and authorization.get('mode') != 'migration':
            raise ValueError(f"Type is required unless status is reference or inactive: {', '.join(TYPES)}")
        if errors := field_errors(asset):
            raise ValueError('; '.join(errors))
        if not isinstance(expected_revision, int) or expected_revision < 0:
            raise ValueError('Expected revision must be a nonnegative integer')
        if case is not None:
            if errors := case_errors(case):
                raise ValueError('; '.join(errors))
            case = dict(case, needs=[dict(n, assets=n.get('assets') or [asset['id']]) for n in case['needs']])
            if self.case_file(case['id']).exists():
                raise ValueError(f"Case {case['id']} exists; choose another id")
        body = json.dumps(asset, ensure_ascii=False, sort_keys=True)
        recorded_at = datetime.now(timezone.utc).isoformat()
        with self.connect(write=True) as db:
            db.execute('BEGIN IMMEDIATE')
            current = db.execute('SELECT COALESCE(MAX(revision), 0) FROM revisions WHERE id=?', (asset['id'],)).fetchone()[0]
            if current != expected_revision:
                raise ValueError(f'Revision conflict: expected {expected_revision}, actual {current}')
            row = db.execute('SELECT body FROM revisions WHERE id=? AND revision=?', (asset['id'], current)).fetchone()
            changed_quotes = quote_changes(json.loads(row[0]) if row else None, asset)
            if is_core(asset):
                latest = db.execute('SELECT body FROM revisions r WHERE id<>? AND revision=(SELECT MAX(revision) FROM revisions WHERE id=r.id)', (asset['id'],)).fetchall()
                if sum(is_core(json.loads(b)) for (b,) in latest) >= CORE_LIMIT:
                    raise ValueError(f'Core is limited to {CORE_LIMIT} assets; ask the owner which core asset to drop')
            db.execute('INSERT INTO revisions VALUES (?, ?, ?, ?, ?)', (asset['id'], current + 1, recorded_at, body, json.dumps(authorization, ensure_ascii=False)))
            if case is not None:
                # Same transaction as the revision: both are committed or neither is.
                if db.execute('SELECT 1 FROM cases WHERE id=?', (case['id'],)).fetchone():
                    raise ValueError(f"Case {case['id']} exists; choose another id")
                db.execute('INSERT INTO cases VALUES (?, ?, ?, ?, ?)', (case['id'], asset['id'], current + 1, recorded_at, json.dumps(case, ensure_ascii=False)))
        result = dict(json.loads(body), revision=current + 1, recorded_at=recorded_at, authorization=dict(authorization))
        if case is not None:
            result['case'] = case['id']
        if changed_quotes:
            result['quote_changes'] = changed_quotes  # the write is committed; the host confirms each change was intended
        try:
            exported = self.export_cases()  # also completes any earlier export that was cut short
        except Exception as exc:  # the write is committed; an export problem is reported, never raised
            exported = {'missing': ['?'], 'errors': [str(exc)]}
        if exported.get('errors') or exported.get('missing'):
            result['case_export'] = exported
        return result

    def case_file(self, case_id):
        return self.root / CASES_DIR / f'{case_id}.json'

    def export_cases(self):
        """Write each case saved with a revision to evals/cases unless its file exists, and report what is still missing.

        The database keeps the case as committed; the file is the owner's editable copy that `myos eval` reads. A write
        cut short after commit is completed by the next export, which runs after every write and at every eval.
        Deleting a file brings the committed case back; set "retired": true in the file to drop it from evals.
        """
        written, errors = [], []
        if not self.path.exists():
            return {'written': written, 'missing': [], 'errors': errors}
        try:
            db = self.connect()
            try:
                rows = db.execute('SELECT id, body FROM cases ORDER BY id').fetchall()
            finally:
                db.close()
        except sqlite3.OperationalError as exc:
            if 'no such table: cases' in str(exc):
                return {'written': written, 'missing': [], 'errors': errors}  # a store written before cases existed
            return {'written': written, 'missing': ['?'], 'errors': [f'cannot read saved cases: {exc}']}
        folder = self.root / CASES_DIR
        for case_id, body in rows:
            path = self.case_file(case_id)
            if path.exists():
                continue
            try:
                folder.mkdir(parents=True, exist_ok=True, mode=0o700)
                fd, temporary = tempfile.mkstemp(dir=folder, prefix='.case-')
                try:
                    with os.fdopen(fd, 'w', encoding='utf-8') as f:
                        f.write(json.dumps(json.loads(body), ensure_ascii=False, indent=1))
                    os.link(temporary, path)  # fails if the file appeared meanwhile; never overwrites
                finally:
                    Path(temporary).unlink(missing_ok=True)
                written.append(str(path))
            except FileExistsError:
                continue
            except OSError as exc:
                errors.append(f'{case_id}: {exc}')
        stale = time.time() - 3600
        for leftover in folder.glob('.case-*') if folder.is_dir() else []:
            try:
                if leftover.stat().st_mtime < stale:
                    leftover.unlink()  # left by an export that was killed; never loaded as a case
            except OSError:
                pass
        missing = [case_id for case_id, _ in rows if not self.case_file(case_id).exists()]
        return {'written': written, 'missing': missing, 'errors': errors}

    def check(self, *, strict=False):
        if not self.path.exists():
            raise ValueError('No cognition store; initialize through an authorized write or migration')
        with self.connect() as db:
            integrity = db.execute('PRAGMA integrity_check').fetchone()[0]
            rows = db.execute('SELECT id, revision, body, authorization FROM revisions ORDER BY id, revision').fetchall()
        errors = []
        expected = {}
        for key, revision, body, auth in rows:
            expected[key] = expected.get(key, 0) + 1
            a, authorization = json.loads(body), json.loads(auth)
            if revision != expected[key] or a.get('id') != key or a.get('status') not in STATUSES or not a.get('sources') or not authorization.get('source') or not authorization.get('request'):
                errors.append(f'Invalid revision: {key}:{revision}')
        # History cannot be amended, so the use fields are checked on each asset's latest revision.
        latest = {}
        for key, revision, body, _ in rows:
            latest[key] = (revision, json.loads(body))
        for key, (revision, a) in latest.items():
            errors += [f'Invalid revision: {key}:{revision}: {e}' for e in field_errors(a)]
        if (core := sum(is_core(a) for _, a in latest.values())) > CORE_LIMIT:
            errors.append(f'Core has {core} assets; the limit is {CORE_LIMIT}')
        manifest = self.root / 'migration.json'
        if manifest.exists():
            from .migrate import digest
            import hashlib
            manifest_data = json.loads(manifest.read_text())
            saved = {(key, revision): body for key, revision, body, _ in rows}
            for entry in manifest_data.get('imported_revisions', []):
                body = saved.get((entry['id'], entry['revision']))
                if body is None or hashlib.sha256(body.encode()).hexdigest() != entry['sha256']:
                    errors.append(f"Migrated revision mismatch: {entry['id']}:{entry['revision']}")
            for name, item in manifest_data['sources'].items():
                p = self.root / 'originals' / name
                if not p.is_file() or digest(p) != item['sha256']:
                    errors.append(f'Archive mismatch: {name}')
        if integrity != 'ok':
            errors.append(integrity)
        if strict and errors:
            raise ValueError('; '.join(errors))
        # Budgets for what hosts load every session; over budget is a warning, never a write refusal.
        warnings = [f"Core asset {key} has {len(a['content'])} characters; the budget is {CORE_CHAR_BUDGET}"
                    for key, (_, a) in latest.items() if is_core(a) and len(a.get('content', '')) > CORE_CHAR_BUDGET]
        if rows and (lines := self.compile().count('\n')) > BRIEF_LINE_BUDGET:
            warnings.append(f'The compiled block has {lines} lines; the budget is {BRIEF_LINE_BUDGET}')
        return {'integrity': integrity, 'revisions': len(rows), 'errors': errors, 'warnings': warnings, 'semantic_truth_verified': False}

    def references(self, path=None):
        if path is None:
            index = self.root / 'references.json'
            return json.loads(index.read_text()) if index.exists() else []
        source_path, marker, line_text = path.rpartition('#L')
        line = None
        if marker:
            if not re.fullmatch(r'[1-9][0-9]*', line_text):
                raise ValueError('Source line must be a positive integer: #L1, #L2, ...')
            line = int(line_text)
        else:
            source_path = path
        archive = (self.root / 'originals').resolve()
        candidate = (self.root / source_path).resolve()
        if not candidate.is_relative_to(archive) or not candidate.is_file():
            raise ValueError('Source must be a file within this store originals directory')
        content = candidate.read_text()
        if line is not None:
            lines = content.splitlines(keepends=True)
            if line > len(lines):
                raise ValueError('Source line is outside the archived file')
            return {'path': path, 'line': line, 'content': lines[line - 1]}
        return {'path': path, 'content': content}
