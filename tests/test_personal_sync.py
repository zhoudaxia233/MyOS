"""Host sync replaces only the MyOS block, checks every target first, backs up and can revert."""
import asyncio
import json
import os
import subprocess
import sys

import pytest

from myos.personal import sync
from myos.personal.store import BRIEF_LINE_BUDGET, CORE_CHAR_BUDGET, EXPORT_BEGIN, EXPORT_END, Store
from tests.test_personal_store import AUTH, asset

BEFORE = 'You are an expert.\n\n## Working agreements\n\n- Keep my structure.\n\n'
AFTER = '\n\n## Afterwards\n\nOwner text stays.\n'
OLD = f'{EXPORT_BEGIN}\n## old block\n{EXPORT_END}'
LEGACY = '<!-- BEGIN MYOS CORE: generated by `myos export-core`; edit assets, not this block -->\n## MyOS core\n<!-- END MYOS CORE -->'


def store_with(tmp_path, **updates):
    s = Store(tmp_path / 'store')
    s.put(dict(asset(), id='send', title='Final click is mine', type='boundary', status='adopted', core=True, **updates),
          expected_revision=0, authorization=AUTH)
    return s


def host_file(path, block=OLD, mode=0o600):
    path.write_text(BEFORE + block + AFTER)
    path.chmod(mode)
    return path


def cli(root, *args, env=None):
    return subprocess.run([sys.executable, '-m', 'myos', '--data', str(root), *args], capture_output=True, text=True,
                          env=dict(os.environ, **(env or {})))


def test_crlf_files_keep_their_line_endings_and_revert_exactly(tmp_path):
    s = store_with(tmp_path, content='first\r\nsecond')
    original = (BEFORE + OLD + AFTER).replace('\n', '\r\n').encode()
    claude = tmp_path / 'CLAUDE.md'
    claude.write_bytes(original)
    sync.sync(s, [claude])
    data = claude.read_bytes()
    head, tail = BEFORE.replace('\n', '\r\n').encode(), AFTER.replace('\n', '\r\n').encode()
    assert data.startswith(head) and data.endswith(tail) and b'\n' not in data.replace(b'\r\n', b'')
    assert b'\r\r' not in data and b'first\r\nsecond' in data
    assert sync.sync(s, [claude])['targets'][0]['status'] == 'unchanged'
    sync.revert(s, [claude])
    assert claude.read_bytes() == original


def test_write_replaces_only_the_block_backs_up_and_keeps_the_mode(tmp_path):
    s = store_with(tmp_path)
    claude, codex = host_file(tmp_path / 'CLAUDE.md'), host_file(tmp_path / 'AGENTS.md', block=LEGACY, mode=0o644)
    result = sync.sync(s, [claude, codex])
    assert [t['status'] for t in result['targets']] == ['updated', 'updated']
    for path in (claude, codex):
        text = path.read_text()
        assert text.startswith(BEFORE) and text.endswith(AFTER)
        assert text[len(BEFORE):len(text) - len(AFTER)] == s.compile().rstrip('\n')
        assert '## Core (always applies where it fits)' in text and 'MYOS CORE' not in text
    assert claude.stat().st_mode & 0o777 == 0o600 and codex.stat().st_mode & 0o777 == 0o644
    backups = sorted((s.root / sync.BACKUP_DIR).iterdir())
    assert len(backups) == 2 and {b.read_text() for b in backups} == {BEFORE + OLD + AFTER, BEFORE + LEGACY + AFTER}
    assert (s.root / sync.BACKUP_DIR).stat().st_mode & 0o777 == 0o700
    # Nothing changed, so nothing is written or backed up.
    assert [t['status'] for t in sync.sync(s, [claude, codex])['targets']] == ['unchanged', 'unchanged']
    assert len(list((s.root / sync.BACKUP_DIR).iterdir())) == 2


def test_dry_run_shows_the_diff_and_writes_nothing(tmp_path):
    s = store_with(tmp_path)
    claude = host_file(tmp_path / 'CLAUDE.md')
    result = sync.sync(s, [claude], dry_run=True)
    assert result['targets'][0]['status'] == 'would update' and '+### Final click is mine (boundary)' in result['targets'][0]['diff']
    assert claude.read_text() == BEFORE + OLD + AFTER and not (s.root / sync.BACKUP_DIR).exists()


@pytest.mark.parametrize('content, problem', [
    ('No markers here\n', 'exactly one MyOS block'),
    (BEFORE + OLD + '\n' + OLD + AFTER, 'exactly one MyOS block'),
    (BEFORE + OLD + '\n' + LEGACY + AFTER, 'exactly one MyOS block'),
    (f'{EXPORT_END}\n{EXPORT_BEGIN}\n', 'END marker comes before BEGIN'),
])
def test_a_bad_target_leaves_every_target_untouched(tmp_path, content, problem):
    s = store_with(tmp_path)
    good = host_file(tmp_path / 'CLAUDE.md')
    bad = tmp_path / 'AGENTS.md'
    bad.write_text(content)
    with pytest.raises(ValueError, match=problem):
        sync.sync(s, [good, bad])
    assert good.read_text() == BEFORE + OLD + AFTER and bad.read_text() == content
    assert not (s.root / sync.BACKUP_DIR).exists()


def test_symlinks_missing_files_and_no_targets_are_refused(tmp_path):
    s = store_with(tmp_path)
    real = host_file(tmp_path / 'real.md')
    link = tmp_path / 'CLAUDE.md'
    link.symlink_to(real)
    for targets, problem in (([link], 'symlink'), ([tmp_path / 'missing.md'], 'existing regular file'), ([], 'No sync targets')):
        with pytest.raises(ValueError, match=problem):
            sync.sync(s, targets)
    assert real.read_text() == BEFORE + OLD + AFTER


def test_revert_restores_the_latest_backup_and_backups_are_pruned(tmp_path):
    s = store_with(tmp_path)
    claude = host_file(tmp_path / 'CLAUDE.md')
    with pytest.raises(ValueError, match='No backup'):
        sync.revert(s, [claude])
    for n in range(sync.KEEP_BACKUPS + 2):
        s.put(dict(asset(), id='send', title=f'Final click {n}', type='boundary', status='adopted', core=True), expected_revision=n + 1, authorization=AUTH)
        sync.sync(s, [claude])
    assert len(list((s.root / sync.BACKUP_DIR).iterdir())) == sync.KEEP_BACKUPS
    latest = claude.read_text()
    sync.revert(s, [claude])
    reverted = claude.read_text()
    assert reverted != latest and f'Final click {sync.KEEP_BACKUPS}' in reverted and reverted.endswith(AFTER)


def test_cli_targets_come_from_flags_or_the_environment(tmp_path):
    s = store_with(tmp_path)
    claude = host_file(tmp_path / 'CLAUDE.md')
    listing = json.loads(cli(s.root, 'compile', '--list-targets', '--target', str(claude)).stdout)
    assert listing == {'targets': [{'path': str(claude.resolve()), 'ready': True, 'up_to_date': False}]}
    dry = cli(s.root, 'compile', '--dry-run', env={'MYOS_SYNC_TARGETS': str(claude)})
    assert dry.returncode == 0 and json.loads(dry.stdout)['targets'][0]['status'] == 'would update'
    assert claude.read_text() == BEFORE + OLD + AFTER
    written = json.loads(cli(s.root, 'compile', '--write', '--target', str(claude)).stdout)
    assert written['targets'][0]['status'] == 'updated' and 'Final click is mine' in claude.read_text()
    assert json.loads(cli(s.root, 'compile', '--revert', '--target', str(claude)).stdout)['targets'][0]['status'] == 'restored'
    assert claude.read_text() == BEFORE + OLD + AFTER
    assert cli(s.root, 'compile', '--write').returncode == 2  # no targets anywhere
    assert cli(s.root, 'compile').stdout == s.compile()  # plain compile still prints the block


def test_a_write_refreshes_configured_hosts_and_reports_problems_without_failing(tmp_path, monkeypatch):
    s = store_with(tmp_path)
    claude = host_file(tmp_path / 'CLAUDE.md')
    payload = tmp_path / 'payload.json'
    payload.write_text(json.dumps({'asset': dict(asset(), id='side', title='Take my side', type='principle', status='adopted'),
                                   'expected_revision': 0, 'authorization': AUTH}))
    plain = json.loads(cli(s.root, 'put', str(payload)).stdout)
    assert 'host_sync' not in plain and claude.read_text() == BEFORE + OLD + AFTER
    payload.write_text(json.dumps({'asset': dict(asset(), id='side', title='Take my side', type='principle', status='adopted'),
                                   'expected_revision': 1, 'authorization': AUTH}))
    synced = json.loads(cli(s.root, 'put', str(payload), env={'MYOS_SYNC_TARGETS': str(claude)}).stdout)
    assert synced['revision'] == 2 and synced['host_sync']['targets'][0]['status'] == 'updated'
    assert '- Take my side (principle, id `side`)' in claude.read_text()
    # A broken target is reported; the write itself stands.
    claude.write_text('markers removed\n')
    payload.write_text(json.dumps({'asset': dict(asset(), id='side', title='Take my side', type='principle', status='adopted'),
                                   'expected_revision': 2, 'authorization': AUTH}))
    broken = json.loads(cli(s.root, 'put', str(payload), env={'MYOS_SYNC_TARGETS': str(claude)}).stdout)
    assert broken['revision'] == 3 and 'exactly one MyOS block' in broken['host_sync']['error']


def test_mcp_put_refreshes_configured_hosts(tmp_path):
    from mcp import ClientSession, StdioServerParameters
    from mcp.client.stdio import stdio_client
    s = store_with(tmp_path)
    claude = host_file(tmp_path / 'CLAUDE.md')

    async def run():
        config = StdioServerParameters(command=sys.executable, args=['-m', 'myos.personal.mcp'],
                                       env=dict(os.environ, MYOS_DATA_DIR=str(s.root), MYOS_SYNC_TARGETS=str(claude)))
        async with stdio_client(config) as (reader, writer):
            async with ClientSession(reader, writer) as session:
                await session.initialize()
                return await session.call_tool('myos_put', {'asset': dict(asset(), id='side', title='Take my side', type='principle', status='adopted'),
                                                            'expected_revision': 0, 'authorization': AUTH})
    result = asyncio.run(run())
    assert not result.isError
    assert json.loads(result.content[0].text)['host_sync']['targets'][0]['status'] == 'updated'
    assert '- Take my side (principle, id `side`)' in claude.read_text()


def test_check_warns_when_the_always_loaded_block_exceeds_its_budget(tmp_path):
    s = store_with(tmp_path)
    assert s.check()['warnings'] == []
    s.put(dict(asset(), id='send', title='Final click is mine', type='boundary', status='adopted', core=True, content='x' * (CORE_CHAR_BUDGET + 1)),
          expected_revision=1, authorization=AUTH)
    for n in range(BRIEF_LINE_BUDGET):
        s.put(dict(asset(), id=f'entry-{n}', title=f'Entry {n}', type='method', status='adopted'), expected_revision=0, authorization=AUTH)
    checked = s.check(strict=True)  # budgets warn; they never fail a strict check
    assert checked['errors'] == []
    assert any('Core asset send has' in w for w in checked['warnings'])
    assert any('The compiled block has' in w for w in checked['warnings'])
